const TRANSLATIONS: Record<string, Partial<Record<ErrorCode, string>>> = {
  en: Object.fromEntries(
    Object.values(ErrorCode).map((code) => [code, ERROR_CATALOG[code].message]),
  ),
  es: ES,
  fr: FR,
};

function buildCodesSection(language: string): Record<string, string> {
  const dict = TRANSLATIONS[language] ?? TRANSLATIONS.en;
  const out: Record<string, string> = {};
  for (const code of Object.values(ErrorCode)) {
    out[code] = dict[code] ?? TRANSLATIONS.en[code]!;
  }
  return out;
}

const LOCALES_DIR = path.join(__dirname, "..", "src", "locales");
const TARGET_LANGUAGES = ["en", "es", "fr"];

for (const language of TARGET_LANGUAGES) {
  const filePath = path.join(LOCALES_DIR, language, "errors.json");
  let existing: Record<string, unknown> = {};
  if (fs.existsSync(filePath)) {
    existing = JSON.parse(fs.readFileSync(filePath, "utf8"));
  }
  const merged = {
    ...existing,
    codes: buildCodesSection(language),
  };
  fs.writeFileSync(filePath, JSON.stringify(merged, null, 2) + "\n", "utf8");
  console.log(`Updated ${filePath} (${Object.keys(merged.codes).length} codes)`);
}
